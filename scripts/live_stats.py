#!/usr/bin/env python3
"""
live_stats.py — regenerates the <!--LIVE_STATS_START-->…<!--LIVE_STATS_END-->
block in README.md using data from the GitHub API.

Environment variables:
  GH_TOKEN   — PAT or GITHUB_TOKEN (auto-injected by Actions)
  GH_REPO    — "owner/repo"  (auto-injected by Actions)
"""
import os, json, re, datetime as dt, urllib.request, urllib.error
from pathlib import Path

TOKEN   = os.environ.get("GH_TOKEN", "")
REPO    = os.environ.get("GH_REPO", "")        # e.g. "Sp2736/mastery-os"
ROOT    = Path(__file__).resolve().parent.parent
IST     = dt.timezone(dt.timedelta(hours=5, minutes=30))

def api(path, token=TOKEN):
    suffix = f"/{path.lstrip('/')}" if path else ""
    url = f"https://api.github.com/repos/{REPO}{suffix}"
    h = {
        "User-Agent": "live-stats",
        "Accept": "application/vnd.github+json",
    }
    if token:
        h["Authorization"] = f"Bearer {token}"
    with urllib.request.urlopen(urllib.request.Request(url, headers=h), timeout=20) as r:
        return json.load(r)

def graphql(query, variables=None):
    h = {
        "User-Agent": "live-stats",
        "Accept": "application/json",
        "Content-Type": "application/json",
    }
    if TOKEN:
        h["Authorization"] = f"Bearer {TOKEN}"
    data = json.dumps({"query": query, "variables": variables or {}}).encode()
    req = urllib.request.Request("https://api.github.com/graphql", data=data, headers=h)
    with urllib.request.urlopen(req, timeout=20) as r:
        return json.load(r)

# ── fetch data ─────────────────────────────────────────────────────────────

def latest_commits(n=10):
    commits = api(f"commits?per_page={n}")
    rows = []
    for c in commits:
        sha   = c["sha"][:7]
        msg   = c["commit"]["message"].splitlines()[0][:72]  # first line, capped
        date  = c["commit"]["committer"]["date"][:10]
        url   = c["html_url"]
        rows.append(f"| [`{sha}`]({url}) | {msg} | {date} |")
    return rows

def repo_meta():
    return api("")   # returns full repo object

def languages():
    d = api("languages")
    total = sum(d.values()) or 1
    return [(lang, round(100 * size / total, 1)) for lang, size in
            sorted(d.items(), key=lambda kv: -kv[1])]

def open_issues_prs():
    repo = repo_meta()
    return repo.get("open_issues_count", 0)   # GitHub counts both issues + PRs here

# ── build markdown ─────────────────────────────────────────────────────────

def build_block():
    now = dt.datetime.now(IST).strftime("%d %b %Y, %I:%M %p IST")
    
    # repo meta
    meta = repo_meta()
    stars   = meta.get("stargazers_count", 0)
    forks   = meta.get("forks_count", 0)
    watchers= meta.get("watchers_count", 0)
    size_kb = meta.get("size", 0)
    open_i  = meta.get("open_issues_count", 0)
    default = meta.get("default_branch", "main")
    
    lines = [
        f"<!-- auto-generated by live_stats.py — do not edit this block manually -->",
        f"",
        f"### 📊 Live Stats &nbsp;·&nbsp; <sub>last updated {now}</sub>",
        f"",
        f"| ⭐ Stars | 🍴 Forks | 👁 Watchers | 📋 Open Issues/PRs | 💾 Repo Size |",
        f"|---|---|---|---|---|",
        f"| {stars} | {forks} | {watchers} | {open_i} | {size_kb:,} KB |",
        f"",
    ]
    
    # language bar
    langs = languages()
    if langs:
        lines.append("**Languages**")
        bar_parts = []
        for lang, pct in langs[:8]:
            bar_parts.append(f"`{lang}` {pct}%")
        lines.append("  ".join(bar_parts))
        lines.append("")
    
    # latest commits
    try:
        commits = latest_commits(10)
        lines += [
            "**Latest 10 commits**",
            "",
            "| Commit | Message | Date |",
            "|---|---|---|",
        ] + commits + [""]
    except Exception as e:
        print("commits fetch failed:", e)
    
    return "\n".join(lines)

def patch_readme(block):
    readme = ROOT / "README.md"
    text = readme.read_text(encoding="utf-8")
    
    start_tag = "<!--LIVE_STATS_START-->"
    end_tag   = "<!--LIVE_STATS_END-->"
    
    if start_tag not in text:
        # append the section if markers not found
        text += f"\n\n---\n\n{start_tag}\n{block}\n{end_tag}\n"
    else:
        pat = re.compile(
            rf"{re.escape(start_tag)}.*?{re.escape(end_tag)}", re.S
        )
        text = pat.sub(f"{start_tag}\n{block}\n{end_tag}", text)
    
    readme.write_text(text, encoding="utf-8")
    print("README patched successfully.")

if __name__ == "__main__":
    block = build_block()
    patch_readme(block)
